//! Build script. With `--features embed`, it lists every file in assets/ so the game can
//! carry them inside the executable (see `assets::try_read`). Without it, the list is
//! empty and the game reads the assets folder as usual.

use std::path::Path;

fn walk(dir: &Path, root: &Path, out: &mut Vec<(String, String)>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir).unwrap().flatten().collect();
    entries.sort_by_key(|e| e.path());
    for e in entries {
        let p = e.path();
        if p.is_dir() {
            walk(&p, root, out);
        } else {
            let rel = p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
            out.push((rel, p.canonicalize().unwrap().to_string_lossy().replace('\\', "/")));
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let mut files = Vec::new();
    if std::env::var("CARGO_FEATURE_EMBED").is_ok() {
        println!("cargo:rerun-if-changed=assets");
        walk(Path::new("assets"), Path::new("assets"), &mut files);
    }
    let mut code = String::from("// generated by build.rs\npub static FILES: &[(&str, &[u8])] = &[\n");
    for (rel, abs) in &files {
        code += &format!("    ({rel:?}, include_bytes!({abs:?})),\n");
    }
    code += "];\n";
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("embedded.rs");
    std::fs::write(out, code).unwrap();
}
